"""Отвечает на вопросы по работе со STASH."""

# 1. Что делает команда git stash?
# Временно откладывает все незакоммиченные изменения из текущей рабочей директории в отдельное хранилище (в некий "буфер обмена"), возвращая файлы к состоянию последнего коммита без создания нового коммита.
#
# 2. Как просмотреть список всех сохранённых изменений (стэшей)?
# git stash list
#
# 3. Какая команда применяется для использования верхнего стэша?
# Можно использовать либо "git stash pop", либо "git stash apply"
#
# 4. Как применить конкретный стэш по его номеру?
# Для этого можно воспользоваться командой "git stash apply stash@{n}", где n - индекс из списка git stash list.
#
# 5. Чем отличается команда git stash apply от git stash pop?
# git stash apply — применяет изменения из стэша к рабочей директории, но оставляет сам стэш в списке (можно применить ещё раз, в том числе к другой ветке);
#
# git stash pop — применяет изменения и, в отличие от apply, сразу удаляет этот стэш из списка
#
# 6. Что делает команда git stash drop?
# Удаляет конкретный стэш из списка без применения его изменений. Например,
#
# git stash drop stash@{1}
#
# 7. Как полностью очистить все сохранённые стэши?
# Командой git stash clear
#
# 8. В каких случаях удобно использовать git stash?
#
# - Нужно срочно переключиться на другую ветку, а текущая работа ещё не готова к коммиту
#
# - Нужно сделать pull, а незакоммиченные изменения могут конфликтовать с входящими
#
# - Хочешь протестировать что-то на "чистом" состоянии проекта, не теряя текущий черновик
#
# - Хочешь быстро "отложить" эксперимент, не засоряя историю коммитов недоделанной работой
#
# 9. Что произойдёт, если выполнить git stash pop, но в проекте есть конфликтующие изменения?
# Если, пока изменения лежали в стэше, файл успел измениться другим способом (например, через merge/pull) в тех же самых строках — git не сможет применить их автоматически и покажет конфликт слияния. Также стоит учесть и то, что при конфликте сам стэш не удаляется из списка (в отличие от обычного успешного pop) — на всякий случай, чтобы не потерять его, пока конфликт не разрешён.
#
# 10. Можно ли восстановить удалённый стэш после выполнения git stash drop?
# Формально — да, но не гарантированно и не просто. Git физически не уничтожает данные сразу, они какое-то время остаются в внутренней базе объектов git. Восстановить можно через:
#
# git fsck --unreachable
#
# Найти там нужный хеш commit-подобного объекта стэша, а потом:
#
# git stash apply хеш_объекта
#
# Но это не гарантировано (garbage collection git может со временем окончательно удалить неиспользуемые объекты) и требует ручного поиска
#
# 11. Что делает команда git stash save "NAME_STASH"
# Создаёт стэш с указанным именем/описанием вместо стандартного автоматического сообщения вида "WIP on main". Удобно, когда стэшей много и нужно потом легко понять, какой из них что содержит, глядя на git stash list.
#
# 12. Что делает команда git stash apply "NUMBER_STASH"
# Применяет к рабочей директории изменения из конкретного стэша по его номеру/индексу, не удаляя его из списка.
#
# 13. Что делает команда git stash pop "NUMBER_STASH"
# Применяет изменения из конкретного стэша по номеру и сразу удаляет его из списка после успешного применения.
