# 9 Что такое и зачем нужен файл README
# Файл README может быть в любом формате, который GitHub в состоянии распознать. Например, это может быть README, README.md, README.asciidoc и так далее. Если GitHub увидит такой файл в вашем исходном коде, то отобразит его на заглавной странице проекта.
# Большинство команд используют его для поддержания актуальной информации о проекте
# для новичков. Как правило, он включает следующее:
# • Для чего предназначен проект
# • Инструкции по конфигурации и установке
# • Примеры использования
# • Используемую лицензию
# • Правила участия в проекте
#
# 9.1 Что такое и зачем нужен файл CONTRIBUTING (Рисунок 122)
# Если в вашем репозитории будет файл CONTRIBUTING с любым расширением, то GitHub будет показывать ссылку на него при создании любого запроса на слияние.
# Идея состоит в том, что вы можете указать конкретные вещи, которые вы хотите или не хотите видеть в новых запросах на слияние. Таким образом люди могут ознакомится с руководством, перед тем как создавать новый запрос на слияние.
