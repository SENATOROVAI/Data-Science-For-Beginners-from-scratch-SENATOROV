# 1.1 Что такое GitHub?
# GitHub — это крупнейшее хранилище Git репозиториев, а так же центр сотрудничества для
# миллионов разработчиков и проектов.
#
# 1.2. Как GitHub связан с Git?
# Git — это система контроля версий (программа/формат хранения истории кода).
# GitHub — это веб‑сервис, который хранит репозитории Git в облаке и добавляет вокруг них удобный интерфейс и дополнительные функции.
#
# 1.3. Чем отличается fork репозитория от его клонирования (clone)?
# Fork — это копия репозитория на сервере в свой аккаунт, а Clone - копирование репозитория на локальный компьютер
#
# 1.4. Зачем нужны и как работают pull requests?
# Pull Request (PR) — это способ предложить свои изменения в репозиторий и обсудить их перед тем, как они попадут в основной код.
# Как работает: разработчик создаёт ветку в форке репозитория, вносит свои изменения, коммитит их и отправляет PR в основную ветку. Далее идут обсуждения, правки и в результате изменения из PR вносятся в основую ветку проекта или отклоняются авторами.
#
