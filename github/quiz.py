# 1.1. Что такое GitHub?
#
# Ответ: GitHub - это крупнейшее хранилище Git-репозиториев, а также центр сотрудничества для миллионов разработчиков и проектов, позволяющий разработчикам со всего мира работать над одним кодом одновременно, не мешая друг другу.
#
# 1.2. Как GitHub связан с Git?
# Ответ: Git - это инструмент, локальная система контроля версий, установленная на компьютере пользователя, а GitHub - его облачное хранилище, онлайн-сервис. Git отслеживает изменения локально, а GitHub синхронизирует эти изменения через удаленные репозитории.
#
# 1.3. Чем отличается fork репозитория от его клонирования (clone)?
# Ответ: Fork - это создание копии репозитория на GitHub под своим аккаунтом для независимой разработки и внесения изменений (Pull Request). Clone - это загрузка копии репозитория (форкнутого или оригинального) с сервера на локальный компьютер для работы. Форк нужен для внесения вклада в чужие проекты или создание отдельного проекта.  Clone - для работы с кодом, локального тестирования и коммитов.
#
# 1.4. Зачем нужны и как работают pull requests?
# Ответ: Pull Request (PR) — это механизм в системе контроля версий на GitHub, позволяющий разработчику уведомить коллег о завершении работы над веткой и предложить слияние изменений в основной код. PR нужны для рецензирования кода (code review), обсуждения, тестирования и контроля качества, обеспечивая защиту от ошибок.
# Pull Request работают следующим образом: разработчик создаёт новую ветку для новой фичи или багфикса, вносит изменения и коммитит их в свою ветку, затем создаёт PR, указывая, что хочет слить изменения из своей ветки в целевую. Коллеги просматривают код, оставляют комментарии, автор вносит правки. После одобрения (approval) ответственным лицом изменения вливаются в целевую ветку.
#
# 1.5. GitHub использует ваш почтовый адрес для привязки ваших Git коммитов к вашей учётной записи?
# Ответ: Да, GitHub использует ваш почтовый адрес для привязки ваших Git коммитов к вашей учётной записи. Если вы используете несколько почтовых адресов в своих коммитах и хотите, чтобы GitHub работал с ними корректно, то вам нужно будет добавить все используемые почтовые адреса в секцию под названием «Почтовые адреса» («Emails»), расположенную на вкладке «Администрирование» («Admin»).
#
