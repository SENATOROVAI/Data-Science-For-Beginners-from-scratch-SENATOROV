# 23.6) Практические примеры использования стэша.
#   Краткие сценарии, где стэш помогает.
# git stash — временно прячет текущие незакоммиченные изменения, чтобы рабочая директория стала “чистой”, а потом можно вернуть их назад.
#
# Краткие сценарии, когда стэш реально помогает
# 1. Срочно переключиться на другую задачу / ветку
#     Ты что‑то делаешь в feature-a, но приходит срочный баг в main.
#     git stash               # спрятать текущие незавершённые изменения
#     git checkout main       # перейти на основную ветку
#     (фиксишь баг, коммитишь, пушишь)
#     git checkout feature-a
#     git stash pop           # вернуть свои изменения и продолжить
# 2. Нужно сделать git pull, но есть локальные правки
#     git pull ругается, что есть незакоммиченные изменения.
#     git stash          # спрятать
#     git pull           # обновить код
#     git stash pop      # наложить свои правки поверх свежего кода
# 3. Проверить, “виноваты ли мои изменения” (быстрая диагностика бага)
#     Что‑то сломалось, не уверен — это мой код или уже было.
#     git stash          # убрать мои изменения
#     (запустить тесты / приложение
#     если всё работает → баг в моих изменениях)
#     git stash pop
# 4. Перекинуть черновые правки в другую ветку
#     Начал менять код в main, понял, что надо было в новой ветке.
#     git stash
#     git checkout -b new-feature
#     git stash pop
#     теперь мои изменения в правильной ветке
# 5. Хочешь сохранить эксперимент, но не коммитить “мусор”
#     Сделал кучу пробных изменений, но не хочешь коммитить, зато потом, может, пригодится:
#     git stash save "эксперимент с новой идеей"
#     рабочая директория чистая, можно продолжать
#     git stash list     # посмотреть все стэши
#     git stash pop      # вернуть самый последний
#     git stash apply stash@{2}  # вернуть конкретный стэш
