# 23.3) Различие между стэшем и коммитом.
#   Когда лучше сохранить изменения в стэше, а когда коммитить.
#   Ответ:Коммит
#         Постоянная точка в истории репозитория.
#         Уходит на GitHub при git push.
#         Должен иметь осмысленное сообщение и более‑менее законченные изменения.
#         Видят все, кто работает с репо.
#         Стэш (git stash)
#
#         Временное локальное сохранение незакоммиченных изменений.
#         Не попадает в историю коммитов и на GitHub.
#         Удобен для “черновиков”, переключения задач, экспериментов.
#         Хранится только у тебя локально.
#         Когда стэш лучше:
#         Нужно быстро переключиться на другую ветку/задачу, а текущие правки ещё “сырые”.
#         Надо сделать git pull, но не хочешь сейчас разруливать конфликты.
#         Хочешь проверить, ломают ли код именно твои изменения (убрать → проверить → вернуть).
#         У тебя просто черновой эксперимент, который не готов попадать в историю.
#         Команда: git stash (или с описанием: git stash save "черновик").
#
#         Когда коммит лучше:
#         Изменения:
#         логически закончены (фикс бага, маленькая фича, рефакторинг),
#         полезны тебе или другим в будущем.
#         Хочешь:
#         иметь понятную историю,
#         поделиться кодом через GitHub,
#         уметь вернуться к этому состоянию.
#         Команда: git commit -m "осмысленное сообщение" → потом git push.
