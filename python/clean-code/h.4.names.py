"""Понятные имена в Python.

Конспект главы.
"""

# Конспект главы **«Выбор понятных имён»**:
#
# ---
#
# ### **Основная идея**
# Удачный выбор имён для переменных, функций, классов и прочих сущностей — один из важнейших аспектов написания читаемого, поддерживаемого и понятного кода. Задача субъективная, но ответственная.
#
# ---
#
# ### **Ключевые принципы**
#
# 1. **Имена должны быть содержательными, но не избыточными**
#    - Не используйте слишком короткие (`a`, `b`, `g`) и слишком общие (`data`, `var`, `temp`) имена.
#    - Длинные имена лучше коротких, если они повышают ясность (в первую очередь для глобальных сущностей).
#    - Имя должно отражать назначение: в Python лучше `user_email`, чем просто `email`.
#
# 2. **Следуйте соглашениям PEP 8 по стилю именования**
#    - **Классы**: `PascalCase` (например, `MyClass`).
#    - **Функции, методы, переменные**: `snake_case` (например, `calculate_total`).
#    - **Константы**: `UPPER_SNAKE_CASE` (например, `MAX_SIZE`).
#    - **Приватные атрибуты**: с префиксом `_` (например, `_internal_var`).
#    - **Аргументы методов**: `self` для экземпляров, `cls` для классов.
#
#       Главный фактор удобочитаемости — не сама схема, а последовательность её применения.
#
# 3. **Избегайте вредных практик**
#    - **Не используйте встроенные имена Python** (`list`, `str`, `open`, `id` и т.п.) в качестве имён переменных — это приводит к трудноуловимым ошибкам.
#    - **Не применяйте венгерскую нотацию** (префиксы вроде `strName`, `iCount`) — она устарела.
#    - **Не используйте шутки, каламбуры и культурные отсылки** (`gooseDownload()`) — они непонятны коллегам, особенно не носителям языка.
#
# 4. **Делайте имена пригодными для поиска**
#    - Уникальные и конкретные имена удобнее искать (Ctrl+F), и они реже дают ложные срабатывания.
#
# 5. **Избегайте бессмысленных числовых суффиксов**
#    - Имена вида `payment1`, `payment2` — признак слабой структуры. Лучше вынести данные в коллекцию (`payments = [...]`) или параметризовать вызов (`make_payment(priority=1)`).
#
# 6. **Учитывайте единицы измерения**
#    - Если величина имеет размерность, отражайте её в имени: `weight_kg`, `timeout_sec`. Это помогает избежать серьёзных ошибок (как в случае Mars Climate Orbiter).
#
# 7. **Используйте префиксы `is_`, `has_` для булевых значений**
#    - Например: `is_ready`, `has_permission` — код читается почти как обычная фраза.
#
# ---
#
# ### **Исключения**
# - Однобуквенные имена уместны в ограниченных контекстах: `i`, `j`, `k` — для индексов циклов; `x`, `y` — для координат.
# - Варианты вроде `w` и `h` (width, height) или `n` (number) компактны, но неочевидны для других — используйте их только в очень коротких блоках.
#
# ---
#
# ### **Заключение**
# Хорошие имена — фундамент качественного кода. Они делают код понятным и коллегам, и вам самим через время. Следование рекомендациям (прежде всего PEP 8) и здравый смысл помогают писать код, который удобно читать, поддерживать и развивать.
#
# Подбирайте формулировки так, чтобы код читался как фраза: например, `number_of_trials` читается естественнее, чем `number_trials`.

