# **5. Что делают эти команды?**
# - pip freeze > requirements.txt
# - conda env export > environment.yml
#
# Обе команды выгружают зависимости в файлы. Разница в следующем:
# 1. первая команда работает с venv, вторая - с conda
# 2. вторая команда не просто выгружает зависимости, но и делает полный "слепок" виртуального окружения

# **6. Что делают эти команды?**
# - pip install -r requirements.txt - добавляет пакеты в уже существующее активное окружение
# - conda env create -f environment.yml - создаёт новое окружение с нуля, изолированное, со всеми зависимостями, включая конкретную версию Python

# **7.Что делают эти команды?**
