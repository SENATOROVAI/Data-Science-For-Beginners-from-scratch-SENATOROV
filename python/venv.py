# **1. Что делает команда python -m venv venv?**
#
# Создает виртуальное окружение с именем venv

# **1.1 Что делает каждая команда в списке ниже?**
# - pip list - выводит список зависимостей, установленных в данном виртуальном окружении
# - pip freeze > requirements.txt - выгружает зависимости из текущего виртуального окружения в файл requirements.txt
# - pip install -r requirements.txt - устанавливает зависимости, описанные в requirements.txt, в текущее виртуальное окружение

# **2. Что делает каждая команда в списке ниже?**
# - conda env list - показывает список всех существующих виртуальных окружений сonda
# - conda create -n env_name python=3.5 - создаёт виртуальное окружение с именем env_name и устанавливает в него интерпретатор Python версии 3.5
# - conda env update -n env_name -f file.yml - обновляет указанное окружение на основе описания в file.yml
# - source activate env_name - активирует виртуальное окружение с именем еnv_name
# - source deactivate - деактивирует текущее виртуальное окружение
# - conda clean -a - выполняет полную очистку кэша сonda

