"""Задание на понимание формата сообщений коммитов."""

# 1. Опишите своими словами назначение каждого из этих типов коммитов:
# feat, fix, docs, style, refactor, test, build, ci, perf, chore.
#
# - **feat** — добавление новой функциональности в проект (что-то, чего раньше не было и что видно пользователю/потребителю кода)
#
# - **fix** — исправление бага, то есть починка уже существующей, но неправильно работающей функциональности
#
# - **docs** — изменения только в документации (например, README) — сам код при этом не меняется
#
# - **style** — изменения форматирования/стиля кода (отступы, пробелы, точки с запятой), которые никак не влияют на логику и поведение программы
#
# - **refactor** — изменение внутренней структуры кода (переименование, упрощение, разбиение на функции) без изменения видимого поведения — не баг-фикс и не новая фича, а именно улучшение структуры
#
# - **test** — добавление новых тестов или изменение существующих, без изменений в самом рабочем коде
#
# - **build** — изменения, касающиеся системы сборки проекта или внешних зависимостей (например, правки в pyproject.toml, package.json, конфигах сборщика)
#
# - **ci** — изменения в конфигурации CI/CD
#
# - **perf** — изменения, направленные именно на улучшение производительности (без изменения видимого поведения программы)
#
# - **chore** — рутинные технические задачи, которые не подходят ни под одну из категорий выше (обновление версий зависимостей, мелкая уборка в проекте, правки конфигов, не влияющих ни на сборку, ни на CI)
#
#
