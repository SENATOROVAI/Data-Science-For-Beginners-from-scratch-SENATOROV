# # Ответы по Conventional Commits
#
# ## 1. Назначение типов коммитов
#
# **feat** : добавление новой функциональности.
# Например: добавили новую функцию, кнопку, страницу или возможность в программе.
#
# **fix** : исправление ошибки.
# Используется, когда что-то работало неправильно, и это починили.
#
# **docs** : изменения в документации.
# Например: обновили README, инструкцию или описание функции.
#
# **style** : изменения внешнего вида кода без изменения логики.
# Например: отступы, пробелы, форматирование, переносы строк.
#
# **refactor** : переработка кода без изменения его поведения.
# То есть программа работает так же, но код стал чище, понятнее или удобнее.
#
# **test** : добавление или изменение тестов.
# Например: написали новые тесты или исправили старые.
#
# **build** : изменения, связанные со сборкой проекта или зависимостями.
# Например: изменения в package.json, requirements.txt, Dockerfile или настройках сборки.
#
# **ci** : изменения в настройках автоматических проверок и деплоя.
# Например: GitHub Actions, GitLab CI или другие CI/CD-конфиги.
#
# **perf** : улучшение производительности.
# Используется, когда код стал работать быстрее или эффективнее.
#
# **chore** : технические изменения, которые напрямую не меняют функциональность.
# Например: чистка файлов, обновление конфигов, мелкие служебные правки.
#
