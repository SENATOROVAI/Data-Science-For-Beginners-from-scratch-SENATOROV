# 19. Почему PyPy выполняет код быстрее, чем CPython? PyPy работает быстрее за счёт JIT-компиляции (Just-In-Time). В отличие от CPython, который переводит код по одной строчке на ходу, PyPy анализирует программу прямо во время её работы.
