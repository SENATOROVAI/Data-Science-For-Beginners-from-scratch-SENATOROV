"""Answers for the CPython and PyPy task."""

# # [TASK] Cpython
#
# ## Введение в Python и CPython
#
# 1. Что такое CPython и чем он отличается от Python?
#
# Ответ: Python - это язык программирования, а CPython - это реализация Python и
# одновременно интерпретатор, которым мы обычно пользуемся. CPython написан на
# языке C.
#
# 3. Сколько существует реализаций Python, и какая из них самая популярная?
#
# Ответ: у Python есть 6 реализаций. Самая популярная
# реализация - CPython.
#
# 4. На каком языке написан CPython?
#
# Ответ: CPython написан на языке C.
#
# ## Поиск и установка CPython
#
# 5. Кто создал CPython?
#
# Ответ: Python и CPython создал Guido van Rossum.
#
# 6. Почему Python считается быстрым, несмотря на то, что это интерпретируемый
# язык?
#
# Ответ: CPython написан на C и вызывает инструкции из C. Поэтому многие
# внутренние части интерпретатора работают быстро.
#
# 7. Напишите путь к интерпретатору CPython на вашем компьютере.
#
# Ответ:
#
# ```text
# C:\temp\cpython-3.13.14\PCbuild\amd64\python.exe
# ```
#
# Проверка версии:
#
# ```text
# Python 3.13.14
# implementation=cpython
# ```
#
# ## Структура CPython
#
# 8. Что содержится в папке `include` в CPython?
#
# Ответ: в папке `include` лежат заголовочные файлы `.h`, связанные с C API
# CPython. Например, там есть файл `abstract.h`. Через эти файлы видно, что CPython
# реализован на C.
#
# На этом компьютере папка `include` находится здесь:
#
# ```text
# C:\temp\cpython-3.13.14\Include
# ```
#
# В ней найдено 76 файлов `.h` и 0 файлов `.c`. Примеры файлов: `abstract.h`,
# `boolobject.h`, `bytesobject.h`, `ceval.h`, `compile.h`.
#
# 9. Где можно найти исходный код CPython? Дайте ссылку на репозиторий GitHub.
#
# Ответ:
#
# ```text
# https://github.com/python/cpython
# ```
#
# 10. Как работает интерпретатор CPython при выполнении кода?
#
# Ответ: интерпретатор - это программа, которая читает и запускает код
# построчно.
#
# ## Запуск файла с помощью CPython
#
# 11. Какая команда используется для запуска файла с помощью CPython?
#
# Ответ:
#
# ```powershell
# python путь\до\файла.py
# ```
#
# Если указывать полный путь к собранному интерпретатору:
#
# ```powershell
# C:\temp\cpython-3.13.14\PCbuild\amd64\python.exe путь\до\файла.py
# ```
#
# 12. Можно ли запускать текстовые файлы через интерпретатор Python? Почему?
#
# Ответ: да, можно. Интерпретатору неважно, какое расширение у файла. Главное,
# чтобы внутри файла был корректный Python-код.
#
# 13. Как указать путь к интерпретатору и файлу для выполнения кода?
#
# Ответ: сначала пишем путь до интерпретатора, потом через пробел путь до файла.
#
# ```powershell
# C:\temp\cpython-3.13.14\PCbuild\amd64\python.exe H:\Projects\example.txt
# ```
#
# Если в пути есть пробелы, путь нужно взять в кавычки.
#
# ## Введение в PyPy
#
# 14. Чем PyPy отличается от CPython?
#
# Ответ: PyPy - это другой интерпретатор Python. PyPy работает быстрее CPython,
# но его нельзя применять во всех проектах.
#
# 15. Почему PyPy не может использоваться для всех проектов на Python?
#
# Ответ: PyPy не совместим со всеми Python-проектами. Поэтому его используют не
# везде, а точечно для некоторых проектов.
#
# 16. Где можно скачать PyPy?
#
# Ответ: PyPy можно скачать на официальном сайте:
#
# ```text
# https://www.pypy.org/
# ```
#
# ## Установка и запуск PyPy
#
# 17. Как установить PyPy после скачивания?
#
# Ответ: нужно скачать архив PyPy для своей операционной системы, переместить
# архив в удобное место и распаковать его. После распаковки в папке будет лежать
# интерпретатор PyPy.
#
# 18. Как запустить файл с помощью PyPy?
#
# Ответ: нужно указать путь до интерпретатора PyPy и через пробел путь до файла.
#
# ```powershell
# pypy путь\до\файла.py
# ```
#
# Или полным путем:
#
# ```powershell
# C:\путь\до\pypy.exe H:\Projects\example_pypy.py
# ```
#
# 19. Почему PyPy выполняет код быстрее, чем CPython?
#
# Ответ: PyPy работает быстрее CPython. Главное отличие для задания - PyPy
# быстрее, но подходит не для всех проектов.
