# Введение в PyPy
#
# 14. Чем PyPy отличается от CPython? Главные отличия PyPy от Cpython - это скорость (гораздо быстрее, благодаря JIT компиляции) и совместимость (к сожалению хуже с некоторыми библиотеками, так как написан на Rpython, для запуска библиотек, написанных на си, ему нужно запускать эмулятор, который тормозит и приводит к ошибкам)
# 15. Почему PyPy не может использоваться для всех проектов на Python? Из-за плохой совместимости с некоторыми библиотеками, медленного разогрева (короткие программы обычно медленнее, чем на Cpython), отставание к по отношению к новым версиям языка, более высокое потребление оперативной памяти
