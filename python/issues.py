"""Отвечаем на вопросы про issues."""

# 1. Что такое Issues на GitHub и для чего они используются?
# Issues — это встроенная в GitHub система отслеживания задач, багов и предложений по проекту. По сути, это тикет с заголовком, описанием и обсуждением — используется, чтобы фиксировать "что нужно сделать/починить/обсудить" прямо рядом с кодом, без внешних инструментов.
#
# 2. Чем Issues отличаются от других инструментов управления задачами?
# Главное отличие — глубокая интеграция с самим кодом и git-историей: issue можно напрямую связать с конкретным коммитом, веткой, Pull Request'ом, автоматически закрыть через сообщение коммита. Специализированные таск-трекеры обычно мощнее по функциональности, но требуют отдельного сервиса и настройки интеграции с репозиторием.
#
# 3. Какие основные компоненты (поля) есть у каждого Issue?
# - Title — заголовок, кратко описывающий суть
# - Description (тело) — подробное описание в markdown
# - Labels — метки/теги для классификации
# - Assignees — ответственные за выполнение
# - Milestone — привязка к этапу/релизу
# - Projects — привязка к доске проекта
# - Comments — обсуждение под issue
# - Status — открыт (Open) или закрыт (Closed)
#
# 4. Как создать новое Issue в репозитории?
# Заходим в тот репозиторий, который нас интересует, затем во вкладку Issues репозитория, кнопка "New issue", заполняем заголовок и описание и затем нажимаем "Submit new issue".
#
# 5. Какие данные рекомендуется указывать в описании Issue для лучшего понимания задачи?
# - Чёткое описание проблемы/задачи
# - Шаги для воспроизведения (если это баг)
# - Ожидаемое поведение vs фактическое
# - Скриншоты/логи, если применимо
# - Версия/окружение, где возникла проблема
# - Контекст — почему это важно/приоритет
#
# Также можно отправить часть кода, относительно которого у вас какие-тоо сомнения или вам не понятна.
#
# 6. Какие теги (labels) можно добавить к Issue? Какие из них стандартные?
# - bug — баг
# - documentation — про документацию
# - duplicate — дубликат другого issue
# - enhancement — улучшение/новая фича
# - good first issue — подходит для новичков
# - help wanted — нужна помощь сообщества
# - invalid — некорректный issue
# - question — вопрос
# - wontfix — не будет исправлено
#
# Можно создавать и свои собственные labels под нужды команды.
#
# 7. Как прикрепить Assignees (ответственных) к Issue?
# На странице issue, в правой боковой панели — раздел "Assignees" шестерёнка рядом. Выбираешь пользователя(-ей) из списка участников репозитория.
#
# 8. Как использовать Labels для классификации задач?
# Та же правая панель, раздел "Labels" (либо при нажатии на "New Issue", при создании, открывается окошко, где изначально можно выбрать) выбираешь один или несколько существующих (или создаёшь новый). Используется, чтобы быстро фильтровать issues по типу (баг/фича/вопрос), приоритету, области кода и т.д.
#
# 9. Для чего нужен Milestone, и как связать его с Issue?
# Milestone — это группировка issues/PR вокруг конкретной цели или релиза (например, "Release v2.0", "Sprint 3") с каким-то определённым дедлайном. Показывает прогресс (сколько issues закрыто из общего числа) в виде прогресс-бара. Привязка — та же боковая панель, раздел "Milestone".
#
# 10. Как привязать Issue к пул-реквесту (Pull Request)?
# Есть два способа:
#
# 1) В описании PR написать Closes #12 (или Fixes #12, Resolves #12), где 12 — номер issue
# 2) В боковой панели есть раздел "Development", где можно вручную связать существующий PR
#
# 11. Как добавить комментарий к существующему Issue?
# Просто прокрутить вниз страницы issue и там будет текстовое поле "Add a comment". Пишем текст и затем нажимаем "Comment".
#
# 12. Как закрыть Issue вручную?
# Кнопка "Close issue" внизу страницы issue (рядом с полем комментария).
#
# 13. Можно ли автоматически закрыть Issue с помощью сообщения в коммите или пул-реквесте? Как это сделать?
# Да, можно. В сообщении коммита или в описании Pull Request'а пишем одно из ключевых слов + номер issue:
#
# Fixes #12
# Closes #12
# Resolves #12
#
# Когда такой коммит попадает в основную ветку, issue #12 закроется автоматически.
#
# 14. Как повторно открыть закрытое Issue, если работа ещё не завершена?
# Кнопка "Reopen issue" появляется на месте "Close issue", если issue уже закрыт.
#
# 15. Как найти все открытые или закрытые Issues в репозитории?
# Во вкладке Issues есть переключатель/фильтр вверху: is:open и is:closed. По умолчанию показываются открытые, кликом переключаешься на закрытые.
#
# 16. Как использовать фильтры для поиска Issues по меткам, исполнителям или другим критериям?
# В строке поиска над списком issues используются специальные квалификаторы:
#
# label:bug
# author:username
# milestone:"Release v2.0"
#
# 17. Как сортировать Issues по приоритету, дате создания или другим параметрам?
# В том же месте, где находятся квалификаторы из пункта 16, но в самой правой части есть место для сортировки
#
# 18. Как настроить автоматические уведомления о новых или изменённых Issues?
# Раздел Watch (значок "глаз" на странице репозитория) — можно настроить:
#
# - All Activity — уведомления обо всём, включая issues
# - Нажать "Custom", выбрать конкретно "Issues" и будут уведомления только по ним
#
# 19. Что такое Projects в контексте GitHub, и как связать их с Issues?
# Projects — это доска в стиле Kanban (или таблица/roadmap) для визуального управления задачами — колонки типа "To Do / In Progress / Done". Issues можно добавлять на эту доску (либо вручную, либо автоматически по правилам), карточка при этом синхронизирована с самим issue.
#
# 20. Какие сторонние инструменты можно использовать для автоматизации работы с Issues (например, боты, Webhooks)?
# - Webhooks — репозиторий может отправлять HTTP-запросы на внешний сервер при событиях (создание/закрытие issue). Используется для интеграции со Slack, Discord и т.п.
# - GitHub Actions — можно автоматизировать реакцию на issues прямо внутри GitHub (например, авто-метки по ключевым словам в заголовке).
# - Боты — например, Stale bot (автоматически закрывает неактивные issues), Dependabot (создаёт issues/PR по обновлению зависимостей).
#
# 21. Как упомянуть другого пользователя в комментарии к Issue?
# Просто написать @ + имя пользователя и GitHub подскажет автодополнением. Упомянутый получит уведомление.
#
# 22. Как запросить дополнительные данные или уточнения у автора Issue?
# Просто написать комментарий с вопросом, упомянув автора через @, либо добавить метку типа needs-info/question (если такая заведена в репозитории), чтобы визуально пометить, что issue "висит" в ожидании ответа.
#
# 23. Что делать, если Issue неактуально или его нужно объединить с другим?
# Неактуально — закрыть с меткой wontfix или invalid, с комментарием-объяснением
# Нужно объединить — закрыть с меткой duplicate, оставив комментарий вида "duplicate of #45" со ссылкой на основной issue, куда переносится обсуждение
#
# 24. Как использовать шаблоны для создания Issues?
# В репозитории создаётся папка .github/ISSUE_TEMPLATE/ с markdown-файлами (или YAML-конфигами форм) — при создании нового issue GitHub предложит выбрать один из готовых шаблонов (например, "Bug report", "Feature request") с заранее заданной структурой полей, чтобы автор не забыл ничего важного.
#
# 25. Что такое Linked Issues, и как создать связь между задачами?
# Механизм, при котором issue явно связывается с другим issue или PR (не через закрытие, как в п.13, а именно как "связанная задача"), отображаясь в разделе "Development" в боковой панели — обычно это происходит автоматически, когда в тексте PR/issue упоминается номер другого (#12) или используется ключевое слово связи.
#
# 26. Какие метрики (например, время выполнения) можно отслеживать с помощью Issues?
# - Время от создания до закрытия issue
# - Количество открытых и закрытых за период
# - Активность по меткам (сколько багов vs фич)
# - Нагрузка на конкретных assignees (сколько issues на человека)
#
# 27. Какие best practices рекомендуются при работе с Issues в команде?
# - Один issue = одна конкретная задача/проблема, не смешивать несколько тем в одном
# - Чёткие, поисковые заголовки (не "баг", а "Кнопка отправки не работает на мобильной версии")
# - Использовать шаблоны, чтобы структура описания была единообразной
# - Регулярно расставлять/актуализировать labels и milestones
# - Закрывать issues автоматически через Fixes #N в PR, а не вручную — так история не расходится с реальностью
# - Не давать issues "висеть" бессрочно без ответа
