# # Ответы по работе с Issues на GitHub
#
# ## Общие вопросы
#
# ### 1. Что такое Issues на GitHub и для чего они используются?
#
# Issues это задачи, сообщения об ошибках, предложения новых функций и вопросы, связанные с репозиторием. Они используются для планирования работы, обсуждения изменений и отслеживания выполнения задач.
#
# ### 2. Чем Issues отличаются от других инструментов управления задачами?
#
# Issues непосредственно связаны с GitHub-репозиторием. Их можно связывать с ветками, коммитами, Pull Request, Milestones и Projects. Это позволяет обсуждать задачу и одновременно видеть код, с помощью которого она решается.
#
# В отличие от отдельных систем управления проектами, Issues являются частью процесса разработки и не требуют переноса информации о задаче в другой сервис.
#
# ### 3. Какие основные компоненты есть у каждого Issue?
#
# Основные компоненты Issue:
#
# * уникальный номер;
# * заголовок;
# * описание;
# * автор;
# * состояние Open или Closed;
# * комментарии.
#
# Дополнительно можно указать:
#
# * Assignees;
# * Labels;
# * Milestone;
# * Project;
# * тип задачи;
# * связанные ветки и Pull Request;
# * родительские задачи, подзадачи и зависимости.
#
# ## Создание Issues
#
# ### 4. Как создать новое Issue в репозитории?
#
# Нужно открыть репозиторий, перейти во вкладку **Issues**, нажать **New issue**, выбрать шаблон или пустое Issue, заполнить заголовок и описание, затем нажать **Submit new issue**.
#
# ### 5. Какие данные рекомендуется указывать в описании Issue?
#
# В описании рекомендуется указать:
#
# * суть проблемы или задачи;
# * ожидаемый результат;
# * фактический результат;
# * шаги для воспроизведения ошибки;
# * версию программы и рабочее окружение;
# * примеры кода;
# * текст ошибки и логи;
# * скриншоты;
# * критерии завершения задачи.
#
# Описание должно содержать достаточно информации, чтобы другой участник мог понять и воспроизвести проблему.
#
# ### 6. Какие Labels можно добавить к Issue? Какие из них стандартные?
#
# В репозитории можно создавать собственные Labels, например `priority: high`, `frontend`, `backend`, `testing` или `security`.
#
# Стандартные Labels GitHub:
#
# * `bug`, ошибка;
# * `documentation`, изменение документации;
# * `duplicate`, дубликат;
# * `enhancement`, новая возможность или улучшение;
# * `good first issue`, задача для начинающих;
# * `help wanted`, требуется помощь;
# * `invalid`, некорректное или неактуальное Issue;
# * `question`, вопрос или запрос дополнительной информации;
# * `wontfix`, задача не будет исправляться.
#
# Стандартные Labels можно изменять и удалять.
#
# ### 7. Как прикрепить Assignees к Issue?
#
# Нужно открыть Issue, найти блок **Assignees** в правой части страницы, нажать на него и выбрать пользователя. Assignee показывает, кто отвечает за выполнение задачи. К одному Issue можно назначить несколько исполнителей.
#
# ## Работа с Issues
#
# ### 8. Как использовать Labels для классификации задач?
#
# Labels позволяют группировать Issues по типу, важности, состоянию или области проекта.
#
# Например:
#
# * `bug`, ошибка;
# * `enhancement`, новая возможность;
# * `priority: high`, высокий приоритет;
# * `frontend`, задача интерфейса;
# * `in progress`, задача выполняется;
# * `needs review`, требуется проверка.
#
# После добавления Labels список Issues можно фильтровать по нужным меткам.
#
# ### 9. Для чего нужен Milestone и как связать его с Issue?
#
# Milestone объединяет несколько Issues и Pull Request, относящихся к одной цели, версии или этапу проекта.
#
# Например, Milestone `Version 2.0` может содержать все задачи, которые должны быть завершены перед выпуском этой версии.
#
# Чтобы связать Issue с Milestone, нужно открыть Issue, нажать **Milestone** в правой части страницы и выбрать нужный Milestone. GitHub показывает срок выполнения, количество открытых и закрытых задач и процент готовности Milestone.
#
# ### 10. Как привязать Issue к Pull Request?
#
# В описании Pull Request можно указать ключевое слово и номер Issue:
#
# ```text
# Closes #15
# ```
#
# Также поддерживаются слова:
#
# ```text
# Fixes #15
# Resolves #15
# ```
#
# После слияния Pull Request в основную ветку связанное Issue автоматически закроется.
#
# Связь также можно создать вручную через раздел **Development** в правой части Issue или Pull Request.
#
# ### 11. Как добавить комментарий к существующему Issue?
#
# Нужно открыть Issue, перейти к полю комментария в нижней части страницы, написать текст и нажать **Comment**.
#
# В комментарий можно добавлять Markdown, ссылки, изображения, фрагменты кода, упоминания пользователей и ссылки на другие Issues.
#
# ## Закрытие и завершение Issues
#
# ### 12. Как закрыть Issue вручную?
#
# Нужно открыть Issue и нажать кнопку **Close issue**. При необходимости можно сначала оставить комментарий с объяснением причины закрытия.
#
# ### 13. Можно ли автоматически закрыть Issue с помощью сообщения в коммите или Pull Request?
#
# Да. В описании Pull Request или сообщении коммита нужно использовать ключевое слово и номер Issue:
#
# ```text
# Closes #25
# ```
#
# ```text
# Fixes #25
# ```
#
# ```text
# Resolves #25
# ```
#
# Issue будет автоматически закрыто после попадания соответствующего Pull Request или коммита в основную ветку репозитория.
#
# ### 14. Как повторно открыть закрытое Issue?
#
# Нужно открыть закрытое Issue и нажать **Reopen issue**. После этого его состояние снова изменится на Open.
#
# Перед повторным открытием желательно оставить комментарий и объяснить, почему задача ещё не завершена.
#
# ## Фильтрация и поиск
#
# ### 15. Как найти все открытые или закрытые Issues в репозитории?
#
# Нужно открыть вкладку **Issues** и выбрать состояние **Open** или **Closed**.
#
# Также можно использовать поисковые запросы:
#
# ```text
# is:issue is:open
# ```
#
# ```text
# is:issue is:closed
# ```
#
# Фильтр `is:issue` исключает Pull Request из результатов.
#
# ### 16. Как использовать фильтры для поиска Issues?
#
# В строке поиска можно использовать специальные квалификаторы:
#
# ```text
# is:open
# ```
#
# Только открытые Issues.
#
# ```text
# is:closed
# ```
#
# Только закрытые Issues.
#
# ```text
# label:bug
# ```
#
# Issues с меткой `bug`.
#
# ```text
# assignee:@me
# ```
#
# Issues, назначенные текущему пользователю.
#
# ```text
# author:username
# ```
#
# Issues, созданные определённым пользователем.
#
# ```text
# milestone:"Version 2.0"
# ```
#
# Issues из определённого Milestone.
#
# Фильтры можно объединять:
#
# ```text
# is:issue is:open label:bug assignee:@me
# ```
#
# Такой запрос покажет открытые ошибки, назначенные текущему пользователю.
#
# ### 17. Как сортировать Issues по приоритету, дате создания или другим параметрам?
#
# В списке Issues нужно открыть меню **Sort**.
#
# Доступна сортировка по:
#
# * дате создания, сначала новые или старые;
# * дате обновления;
# * количеству комментариев;
# * количеству реакций.
#
# Отдельной стандартной сортировки по приоритету в обычном списке Issues нет. Приоритет можно обозначить Labels, например `priority: high`, или добавить поле `Priority` в GitHub Projects и сортировать задачи внутри Project.
#
# ## Интеграции и автоматизация
#
# ### 18. Как настроить автоматические уведомления о новых или изменённых Issues?
#
# На странице репозитория нужно открыть меню **Watch**, выбрать **Custom** и включить уведомления для Issues.
#
# Для отдельного Issue можно включить подписку через кнопку **Subscribe**. Уведомления могут отображаться на GitHub или приходить по электронной почте, в зависимости от настроек аккаунта.
#
# ### 19. Что такое Projects и как связать их с Issues?
#
# GitHub Projects это инструмент планирования, в котором задачи можно отображать в виде таблицы, доски или дорожной карты.
#
# В Projects можно использовать:
#
# * статусы;
# * приоритеты;
# * даты;
# * исполнителей;
# * пользовательские поля;
# * фильтры;
# * автоматические рабочие процессы.
#
# Чтобы добавить Issue в Project, нужно открыть Issue, нажать **Projects** в правой части страницы и выбрать нужный проект. Issue также можно добавить непосредственно из самого Project.
#
# ### 20. Какие инструменты можно использовать для автоматизации работы с Issues?
#
# Для автоматизации можно использовать:
#
# * GitHub Actions;
# * GitHub Apps;
# * ботов;
# * Webhooks;
# * REST API;
# * GraphQL API;
# * интеграции с мессенджерами и системами управления проектами.
#
# Например, Webhook может отправить данные на внешний сервер при создании, изменении или закрытии Issue. Бот или GitHub Action может автоматически добавить Label, назначить исполнителя, оставить комментарий или закрыть неактуальную задачу.
#
# ## Коллаборация
#
# ### 21. Как упомянуть другого пользователя в комментарии к Issue?
#
# Нужно написать символ `@` и имя пользователя:
#
# ```text
# @username, проверьте, пожалуйста, эту ошибку.
# ```
#
# Пользователь получит уведомление об упоминании, если это разрешено его настройками.
#
# ### 22. Как запросить дополнительные данные у автора Issue?
#
# Нужно оставить комментарий и конкретно указать, какой информации не хватает.
#
# Например:
#
# ```text
# Пожалуйста, укажите версию Python, операционную систему и полный текст ошибки. Также добавьте шаги, с помощью которых можно воспроизвести проблему.
# ```
#
# При необходимости можно добавить Label `question` или собственную метку `needs more information`.
#
# ### 23. Что делать, если Issue неактуально или его нужно объединить с другим?
#
# Если Issue больше неактуально, нужно оставить комментарий с объяснением и закрыть его.
#
# Если Issue является дубликатом, можно написать:
#
# ```text
# Duplicate of #42
# ```
#
# GitHub создаст связь с основным Issue. После этого дубликат можно закрыть и добавить Label `duplicate`.
#
# GitHub не объединяет содержимое двух Issues в одно автоматически. Нужно выбрать основное Issue, перенести туда важную информацию и закрыть дубликат.
#
# ## Практические аспекты
#
# ### 24. Как использовать шаблоны для создания Issues?
#
# Шаблоны позволяют заранее определить структуру Issue и указать, какую информацию должен предоставить автор.
#
# Шаблоны можно создать через:
#
# ```text
# Settings → General → Features → Issues → Set up templates
# ```
#
# Файлы шаблонов хранятся в каталоге:
#
# ```text
# .github/ISSUE_TEMPLATE/
# ```
#
# Можно создать отдельные шаблоны для ошибок, предложений новых функций и других типов обращений. После добавления шаблонов пользователь выбирает подходящий вариант при создании Issue.
#
# ### 25. Что такое Linked Issues и как создать связь между задачами?
#
# Linked Issues это Issues, между которыми создана логическая связь.
#
# Связь можно создать несколькими способами:
#
# 1. Указать номер другого Issue в описании или комментарии:
#
# ```text
# Связано с #15
# ```
#
# 2. Создать подзадачу через **Create sub-issue**.
#
# 3. Добавить существующее Issue как подзадачу через **Add existing issue**.
#
# 4. Указать зависимость, например что одно Issue блокируется другим.
#
# 5. Связать Issue с веткой или Pull Request через раздел **Development**.
#
# Подзадачи используются для разделения большой задачи на части, а зависимости показывают, какая задача блокирует выполнение другой.
#
# ### 26. Какие метрики можно отслеживать с помощью Issues?
#
# С помощью Issues можно отслеживать:
#
# * количество открытых и закрытых задач;
# * процент выполнения Milestone;
# * время от создания до закрытия;
# * время первого ответа;
# * количество задач, выполненных за определённый период;
# * количество повторно открытых задач;
# * количество задач у каждого исполнителя;
# * распределение задач по Labels;
# * прогресс выполнения подзадач.
#
# GitHub показывает даты создания, обновления и закрытия Issues. Milestones показывают процент выполнения и количество открытых и закрытых задач. Более сложные метрики можно получать через Projects, API или внешние аналитические инструменты.
#
# ### 27. Какие best practices рекомендуются при работе с Issues в команде?
#
# Рекомендуется соблюдать следующие правила:
#
# 1. Создавать одно Issue для одной конкретной задачи.
# 2. Использовать короткий и понятный заголовок.
# 3. Подробно описывать проблему и ожидаемый результат.
# 4. Добавлять шаги воспроизведения для ошибок.
# 5. Использовать единый набор Labels.
# 6. Назначать ответственного исполнителя.
# 7. Связывать Issue с Milestone и Project.
# 8. Связывать коммиты и Pull Request с номером Issue.
# 9. Регулярно обновлять статус задачи.
# 10. Обсуждать изменения в комментариях, чтобы сохранить историю решений.
# 11. Закрывать завершённые и неактуальные Issues.
# 12. Помечать дубликаты и указывать основное Issue.
# 13. Использовать шаблоны для одинакового оформления задач.
# 14. Разбивать крупные задачи на подзадачи.
# 15. Не хранить в Issues пароли, токены и другие конфиденциальные данные.
#
