# ### Наследование
# Принцип *наследования* (inheritance) предполагает, что один класс наследует
# атрибуты и методы другого. В этом случае, говорят про *Родителя* или
# *Суперкласс*
# (parent class, base class) и _Потомка_ или _Подкласс_ (child class, derived
# class)
#
# *Наследование позволяет быстро и без изменения родительского класса
# дополнять его функционал.*
#
# ### Создание родительского класса и класса-потомка
# Создадим класс Animal, который будет включать в себя наиболее общие свойства
# и поведение животных: вес и длину (атрибуты), а также способность питаться и
# спать (методы).


# создадим класс Animal
class Animal:
    """Класс Animal."""

    # пропишем метод .__init__() с двумя параметрами: вес (кг) и длина (см)

    def __init__(self, weight, length):
        """Инициализация."""
        # поместим аргументы этих параметров в соответствующие переменные
        self.weight = weight
        self.length = length

    # объявим методы .eat()
    def eat(self):
        """Метод кушоть."""
        print("Eating")

    # и .sleep()
    def sleep(self):
        """Метод спать."""
        print("Sleeping")


# +
