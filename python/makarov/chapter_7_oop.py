# ## Парадигма программирования
# Парадигма программирования — это, по большому счету, способ организации
# и стиль написания кода. Создание различных парадигм необходимо для того,
# чтобы справиться со все возрастающей сложностью компьютерных программ.
#
# Как вы видите на схеме выше, парадигмы программирования можно разделить
# на две большие группы: *императивное* и *декларативное* программирование
#
# ### Императивное и декларативное программирование
# *Императивное* программирование (imperative programming), как и предполагает
# его
# название (от латинского imperare, «властвовать», «повелевать»), явным образом
# говорит компьютеру, что нужно сделать. Другими словами, мы пишем инструкцию,
# и компьютер строчка за строчкой ее исполняет.
#
# *Декларативный* подход (declarative programming) отличается тем, что детали
# выполнения программы нас не интересуют, для нас важно лишь объяснить
# компьютеру,
# какой результат мы хотим получить.
#
# Языки программирования, соответственно, можно разделить на императивные
# (например, C или Питон) и декларативные (SQL, Haskell). Впрочем, такое
# деление во многом условно, и чуть дальше я покажу вам, что мы, например,
# уже использовали декларативную парадигму внутри Питона.

# ### Процедурное программирование
# Внутри *императивного* программирования выделяют процедурное программирование
# (procedural programming). По большом счету, это обычное программирование,
# которым мы занимались до сегодняшнего занятия. Ставим задачу и
# последовательно
# через набор инструкций приходим к нужному решению.
#
# Впрочем, когда кода и людей его разрабатывающих становится слишком много,
# мы довольно быстро сталкиваемся с недостатками такого подхода. Структура
# кода становится не очевидной, найти ошибку бывает все сложнее и сложнее.
#
# ### Объектно-ориентированное программирование
# В мире ООП все задачи решаются не одной большой программой, а классами
# (и созданными на их основе объектами). Под каждую задачу создается, как
# правило,
# отдельный класс. И хотя поначалу использование классов может показаться
# довольно
# сложным, на самом деле это существенно упрощает решение многих задач.
#
# Более того, изученные выше принципы объектно-ориентированного подхода,
# а именно инкапсуляция, наследование и полиморфизм еще больше способствуют
# грамотной организации кода.
#
# ### Функциональное программирование
# По большому счету, функциональное программирование (functional programming) —
# это набор функций, которые последовательно решают поставленную задачу.
# Результат работы одной функции становится входящим параметром для другой.
#
# *Решение через функциональный подход*
# В частности, решим поставленную выше задачу, вначале последовательно применив
# несколько функций (lambda-функцию, функцию map() и функцию list()) к словарю
# с
# данными о пациентах.

