# ### Переопределение класса
#
# Интересной особенностью класса-потомка в Питоне является то, что он
# переопределяет (по сути, переписывает) родительский класс.
# Давайте создадим подкласс для нелетающих птиц Flightless, в котором:
#
# - единственным атрибутом будет их скорость бега running_speed; а
# - результат метода .move() мы заменим (что логично) с Flying на Running.


# +
# создадим подкласс Flightless класса Bird
class Flightless(Birdv2):
    """Подкласс Flightless класса Bird."""

    # метод .__init__() этого подкласса "стирает" .__init__() родительского
    # класса

    def __init__(self, running_speed):
        """Инициализация объекта."""
        # таким образом, у нас остается только один атрибут
        super().__init__(0, 0, 0)
        self.running_speed = running_speed

    # кроме того, результатом метода .move() будет 'Running'
    def move(self):
        """Метод движение."""
        print("Running")


