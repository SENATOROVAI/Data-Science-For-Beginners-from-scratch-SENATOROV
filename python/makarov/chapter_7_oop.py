# R — это декларативный функциональный язык, специально созданный для обработки
# данных и статистических исследований. Если Питон в основном применяется для
# решения задач бизнеса, то R чаще используется в науке.
#
# На языке R большая часть задач решается с помощью функций, которые
# последовательно
# преобразуют передаваемые им данные. Рассмотрим вот такой пример подсчета
# количества
# мальчиков по имени Тейлор в датасете babynames.
#
# *sum(select(filter(babynames, sex == "M", name == "Taylor"), n))*
#
# Даже если вы первый раз видите код на R довольно несложно догадаться, что в
# данном случае мы (1) с помощью функции filter() находим мальчиков по имени
# Тейлор в датасете babynames, затем (2) отбираем только эти строки через
# select() и (3) наконец складываем результат.
#
# Ту же самую задачу можно реализовать через еще более «функциональный» код с
# использованием оператора %>% (pipeline operator).
#
# # в таком виде последовательность становится еще более наглядной
# babynames %>% filter(sex == "M", name == "Taylor") %>%
#               select(n) %>%
#               sum
#
# По сути мы создали пайплайн (то есть последовательность операций), где
# каждый шаг решается определенной функцией.
