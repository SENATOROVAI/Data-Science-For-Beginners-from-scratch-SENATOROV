# может принимать разные формы. В программировании, полиморфизм предполагает,
# что операторы, функции и объекты могут взаимодействовать с различными типами
# данных.
#
# Например, оператор + в случае чисел предполагает сложение, а в случае строк
# — их объединение.
#
# ### Полиморфизм функций
# Полиморфные функции (polymorphic functions) — это функции, которые могут
