# ## Цикл while
#
# Цикл выполняется пока верно прописанное в нем условие.

# +
# зададим начальное значение счетчика
iii = 0

# пока счетчик меньше трех
while iii < 3:

    # в каждом цикле будем выводить его текущее значение
    print("Текущее значение счетчика:  " + str(iii))

    # внутри цикла не забудем "нарастить" счетчик
    iii = iii + 1

    # и выведем новое значение
    print("Новое значение счетчика:    " + str(iii))

    # добавим пустую строку
    print()

# +
# Небольшой лайфхак. Вместо того, чтобы
# писать i = i + 1 Питон позволяет
# использовать короткую запись
# (shorthand operator): i += 1.

i123 = 0

while i123 < 3:
    print(i123)
    i123 += 1
