# ### Функции range() и enumerate()
# ### Функция range()

# создадим последовательность от 0 до 4
for i in range(5):
    print(i)

# от 1 до 5
for i in range(1, 6):
    print(i)

# и от 0 до 5 с шагом 2 (то есть будем выводить числа через одно)
for i in range(0, 6, 2):
    print(i)

# Функция range() принимает от одного до трех параметров,
#
# - если передать только один параметр, то мы начнем последовательность с нул
#  и закончим на элементе, предшествующем нашему параметру. В примере выше мы
#  передали параметр «пять» (range(5)) и получили последовательность 0, 1, 2,
# 3, 4;
# - если указать два параметра, то мы начнем последовательность с первого
# параметра
# и законим на элементе, предшествующем второму параметру. В частности, если
# написать
# range(1, 6), то получится 1, 2, 3, 4, 5;
# - третий параметр устанавливает шаг. По умолчанию он равен единице, однако
# если,
# например, написать, range(0, 6, 2), то мы получим 0, 2, 4.
#
# Что интересно, если совместить range() с функцией len(), то такую
# конструкцию можно использовать для того, чтобы в одном цикле вывести все
# элементы, например, двух списков по их индексу.

