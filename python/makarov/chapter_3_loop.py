# +
# Интересно, что по последовательности, создаваемой
# функцией range() можно пройтись и в обратном порядке
# от конца к началу. Сделать это можно тремя способами.
#
# Способ 1. Использовать функцию reversed(). Эта функция
# меняет порядок элементов списка на обратный.

# создадим список
my_list = [0, 1, 2, 3, 4]

# передадим его функции reversed() и
# выведем каждый из элементов списка с помощью цикла for
for i in reversed(my_list):
    print(i)

# +
# Одновременно ей можно передать последовательность, создаваемую range() и
# вывести результат в цикле for.

for i in reversed(range(5)):
    print(i)

# +
# Способ 2. Указать
#  в качестве параметра шага. При этом важно, чтобы
# первым параметром указывался конечный элемент списка,
# а вторым — начальный.

for i in range(4, 0, -1):
    print(i)

print()
# Обратите внимание, что в примере выше 4 входит в
# создаваемую последовательность, а вот 0 уже нет.
# Для того чтобы вывести 0, вторым параметром нужно
# также указать

for i in range(4, -1, -1):
    print(i)

# +
# Способ 3. Функция sorted(). Наконец, хотя в
# случае это явно не оптимальный вариант, можно
# использовать функцию sorted(), которая
# сортирует элементы списка по убыванию, если
# передать ей параметр reverse = True.

# создадим последовательность от 0 до 4
rrr = range(5)

# отсортируем ее по убыванию
sorted_values = sorted(rrr, reverse=True)

# выведем элементы отсортированной последовательности
for i in sorted_values:
    print(i)
