# ## Какие типы данных есть в Питоне
#
# Некоторые типы данных позволяют записать только одну единицу
# информации в переменную. К ним, в частности, относятся
#
# - целочисленное значение (integer);
# - десятичная дробь, или если быть более точным, число с плавающей
# запятой (float);
# - комплексное число (complex);
# - строка (string); и
# - логическое значение (boolean).
#
# Также существуют типы данных, в которых могут содержаться
# несколько элементов. Сюда входят:
# - списки (list);
# - словари (dictionary);
# - множества (set); и
# - кортежи (tuple).

# ## Работа с числами

aa = 25  # целое число (int)
bb = 2.5  # число с плавающей точкой (float)
cc = 3 + 25j  # комплексное число (complex)

# float in exp
dd = 2e3  # 2 умножить на 10 в степени 3
print(dd)
print(type(dd))

# ## Операции с числами

# +
# сложение, вычитание, умножение, деление, возведение в степень
print(2 + 2, 4 - 2, 2 * 2, 4 / 2, 2**3)

# разделим 7 на 2, и найдем целую часть и остаток

# целая часть
print(7 // 2)

# остаток от деления
print(7 % 2)

# +
# Также напомню про операторы сравнения.

# больше, меньше, больше или равно и меньше или равно
# print(4 > 2, 4 < 2, 4 >= 2, 4 <= 2)

# равенство
# print(2 == 4)

# и новый для нас оператор неравенства
# print(2 != 4)

# +
# Кроме этого, существуют и чисто логические операции И, ИЛИ и НЕ.

# логическое И, обе операции должны быть истинны
# print(4 > 2 and 2 != 3)

# логическое ИЛИ, хотя бы одна из операций должна быть истинна
# print(4 < 2 or 2 == 2)

# логическое НЕ, перевод истинного значения в ложное и наоборот
# print(not (4 == 4))
