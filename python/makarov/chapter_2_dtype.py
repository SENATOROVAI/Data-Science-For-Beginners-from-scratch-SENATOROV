# ## Методы .strip() и .split()
# Метод .strip() удаляет символы в начале и в конце строки.
# Это бывает полезно, если в базе данных значения записаны,
# например, вместе со служебными символами и от них нужно избавиться.
#
# Метод .split() делит строку на части. По умолчанию, по пробелам,
# но можно указать и другой разделитель.

# +
# применим метод .strip(), чтобы удалить *
print("***15 849 302*****".strip("*"))

# если ничего не указать в качестве аргумента, то удаляются пробелы
# по краям строки
print(" 15 849 302 ".strip())

# применим метод .split(), чтобы разделить строку на части
print(multi_string.split())

# функция len() применима и к спискам
